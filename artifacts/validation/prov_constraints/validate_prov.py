"""
PROV-CONSTRAINTS validation using the Python prov library (v2.1.1).

The Python prov library performs structural validation when loading and
serializing a document: it checks that all referenced entities/activities/agents
exist, that qualified names are well-formed, and that the graph is internally
consistent.  It does NOT implement the full set of W3C PROV-CONSTRAINTS formal
inference rules; for that, ProvToolbox provconvert is required (see commands.txt).

This script:
  1. Loads each document from PROV-JSON.
  2. Round-trips it through PROV-N serialization (exercises additional checks).
  3. Runs prov.unified() which checks type consistency.
  4. Reports specific constraint areas required by the reviewer:
     - assessments with multiple wasGeneratedBy (allowed by PROV)
     - wasAttributedTo between repository and SQAaaS agent
     - Level-2 wasDerivedFrom relations

Outputs:
  prov_library_results.json — per-document summary
  <name>.provn             — PROV-N serialization of each document
"""

import json
import sys
import re
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent.parent.parent

DOCUMENTS = {
    "single_assessment": ROOT / "artifacts" / "paper" / "One_prov_output_enriched.json",
    "full_itwinai":       ROOT / "Provenance_documents" / "interTwin-eu_itwinai_prov_output.json",
    "level2_fc45_4086":   ROOT / "Compare_commit_provenance" / "itwinai_commit_provenance_fc45...fd9c_to_4086...54f4.json",
}


def check_document(name: str, prov_json: dict) -> dict:
    """
    Load and structurally validate a PROV-JSON document.
    Returns a results dict.
    """
    try:
        from prov.model import ProvDocument
        import prov
        prov_version = prov.__version__
    except ImportError:
        return {"name": name, "error": "prov library not installed", "status": "ERROR"}

    result = {
        "name":            name,
        "prov_library":    prov_version,
        "records":         0,
        "load":            "FAIL",
        "provn_serialize": "FAIL",
        "unification":     "FAIL",
        "status":          "FAIL",
        "notes":           [],
        "violations":      [],
    }

    # --- 1. Load ---
    try:
        doc = ProvDocument.deserialize(content=json.dumps(prov_json), format="json")
        records = list(doc.records)
        result["records"] = len(records)
        result["load"] = "PASS"
    except Exception as exc:
        result["violations"].append(f"Load failed: {exc}")
        return result

    # --- 2. PROV-N serialization ---
    try:
        provn_text = doc.get_provn()
        # Save PROV-N file
        provn_path = HERE / f"{name}.provn"
        provn_path.write_text(provn_text, encoding="utf-8")
        result["provn_serialize"] = "PASS"
        result["provn_file"] = str(provn_path)
    except Exception as exc:
        result["violations"].append(f"PROV-N serialization failed: {exc}")

    # --- 3. Unification (type-consistency check) ---
    try:
        _unified = doc.unified()
        result["unification"] = "PASS"
    except Exception as exc:
        result["violations"].append(f"Unification failed (type inconsistency): {exc}")

    # --- 4. Specific constraint areas ---
    entities   = prov_json.get("entity",         {})
    activities = prov_json.get("activity",        {})
    wgb        = prov_json.get("wasGeneratedBy",  {})
    wat        = prov_json.get("wasAttributedTo", {})
    wdf        = prov_json.get("wasDerivedFrom",  {})

    # 4a. Assessments with multiple wasGeneratedBy
    # Each assessment entity is generated by up to 8 QualityCheck activities.
    # PROV allows multiple wasGeneratedBy for the same entity
    # (the uniqueness constraint in PROV-CONSTRAINTS §3 applies only to
    # instantaneous generation events, not to multiple distinct activities).
    entity_wgb_count: dict[str, int] = {}
    for rel_id, rel_val in wgb.items():
        generated_id = rel_val.get("prov:entity", "")
        entity_wgb_count[generated_id] = entity_wgb_count.get(generated_id, 0) + 1

    multi_wgb_entities = [(e, c) for e, c in entity_wgb_count.items() if c > 1]
    if multi_wgb_entities:
        counts_str = ", ".join(f"{e}→{c}" for e, c in sorted(multi_wgb_entities)[:5])
        note = (f"PROV-ALLOWED: {len(multi_wgb_entities)} entities with multiple "
                f"wasGeneratedBy (each assessment has up to 8 QC activities).  "
                f"Examples: {counts_str} … "
                f"This is NOT a PROV-CONSTRAINTS violation: uniqueness of generation "
                f"applies per activity-entity pair, not per entity.")
        result["notes"].append(note)

    # 4b. wasAttributedTo: repository → SQAaaS agent
    wat_count = len(wat)
    result["wasAttributedTo_count"] = wat_count
    # Check it links the repository entity to the SQAaaS agent
    wat_found = False
    for rel_id, rel_val in wat.items():
        entity_ref = rel_val.get("prov:entity",  "")
        agent_ref  = rel_val.get("prov:agent",   "")
        if "SQAaaS" in str(agent_ref):
            wat_found = True
            result["notes"].append(
                f"wasAttributedTo: entity {entity_ref} ← agent {agent_ref} — PRESENT"
            )
    if not wat_found and wat_count > 0:
        result["notes"].append("wasAttributedTo: SQAaaS agent link found but agent name differs from 'SQAaaS'")

    # 4c. Level-2: wasDerivedFrom relations (this document uses wdf, not 'used')
    if "level2" in name:
        wdf_count = len(wdf)
        result["notes"].append(
            f"Level-2 uses wasDerivedFrom ({wdf_count} relations) to link "
            f"file-change activities to commit entities; no 'used' relations "
            f"present in this document version."
        )

    # --- Overall status ---
    if result["violations"]:
        result["status"] = "FAIL"
    elif result["load"] == "PASS" and result["provn_serialize"] == "PASS" and result["unification"] == "PASS":
        result["status"] = "PASS"

    return result


def main():
    results = []
    for name, path in DOCUMENTS.items():
        if not path.exists():
            results.append({"name": name, "status": "SKIP", "note": f"File not found: {path}"})
            print(f"{name}: SKIP (not found)")
            continue

        with open(path, encoding="utf-8") as fh:
            prov_json = json.load(fh)

        r = check_document(name, prov_json)
        results.append(r)

        status_symbol = "✓" if r["status"] == "PASS" else "✗"
        print(f"{status_symbol} {name}: {r['status']}")
        if r.get("violations"):
            for v in r["violations"]:
                print(f"  VIOLATION: {v}")
        if r.get("notes"):
            for n in r["notes"]:
                print(f"  NOTE: {n}")

    out = HERE / "prov_library_results.json"
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2)
    print(f"\nResults saved → {out}")


if __name__ == "__main__":
    main()
